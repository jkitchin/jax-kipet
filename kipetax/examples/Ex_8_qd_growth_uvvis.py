"""
Example 8: Nanoparticle Size Distribution from UV-Vis (Population Balance)

A port of the standalone ``qd_growth_uvvis.py`` demo onto the new
:class:`kipetax.PopulationBalanceModel`. This is the class of problem
``ReactionModel`` cannot express: the state is not a finite species list but a
distribution N(r, t) over particle radius, and the observation is an integral
over that distribution.

Quantum-dot growth. A sectional population balance carries N(r, t): a
prescribed nucleation burst seeds particles at a small radius, diffusion-limited
growth advects them up the size axis, and a monomer mass balance couples every
section (the monomer left in solution is what has not yet condensed onto
particles). The ensemble is watched by UV-Vis through a quantum-confinement
kernel: a particle of radius r has an exciton peak at
lambda_peak(r) = 1240 / (E_bulk + a / r^2), so the spectrum is an integral over
the size distribution weighted by r^3. Recovering N(r) from one spectrum is a
Fredholm integral of the first kind, ill-posed, which is exactly why UV-Vis and
DLS sizing need regularization.

The mechanism IS the regularization. Fitting the two growth parameters
(k_g, A_nuc) to the whole UV-Vis time series ties every time point together and
reconstructs N(r, t), while a naive per-spectrum non-negative inversion, which
sees each spectrum in isolation, collapses. The population balance is integrated
by a differentiable fixed-step upwind Euler scheme (positivity-preserving for
advection), and the fit differentiates through it with JAX autodiff.

NOTE: all data here is SYNTHETIC, generated by the model below. Every radius,
rate, and spectrum comes from the forward model; nothing is measured.
"""
import os

import numpy as np
import jax.numpy as jnp

from kipetax import PopulationBalanceModel

# ── Grid and constants (from the source demo) ──
K = 45
R = np.linspace(0.8, 6.0, K)          # particle radius, nm
DR = float(R[1] - R[0])
LAM = np.linspace(400.0, 720.0, 120)  # wavelength, nm

M0, MEQ, RSTAR, CVOL = 1.0, 0.02, 0.9, 0.9
E_BULK, A_CONF, WIDTH = 1.74, 0.96, 32.0
T0, TAU = 2.0, 0.8
TF, NT = 40.0, 1600
JSTAR = int(np.argmin(np.abs(R - RSTAR)))

KG_TRUE, ANUC_TRUE = 0.018, 0.020

# Quantum-confinement kernel: size ruler + r^3 volume weighting.
LPEAK = 1240.0 / (E_BULK + A_CONF / R ** 2)                       # (K,)
KERNEL = (R ** 3)[None, :] * np.exp(-(LAM[:, None] - LPEAK[None, :]) ** 2
                                    / (2 * WIDTH ** 2))           # (n_lam, K)

T_OBS = np.array([1.5, 2.5, 3.5, 5, 7, 10, 14, 20, 28, 40.0])
IDX_OBS = np.clip((T_OBS / TF * NT).astype(int), 0, NT - 1)

_R = jnp.asarray(R)
_KERNEL = jnp.asarray(KERNEL)
_IDX = jnp.asarray(IDX_OBS)


def step(N, t, p):
    """Sectional PBE right-hand side (upwind advection + nucleation source)."""
    kg, anuc = p['kg'], p['anuc']
    # Monomer mass balance -> supersaturation gates growth.
    m = jnp.maximum(M0 - CVOL * jnp.sum(N * _R ** 3) * DR, MEQ)
    S = m / MEQ
    G = jnp.where(S > 1.0, kg / _R * (S - 1.0), 0.0)
    # Upwind advection (G > 0, backward difference).
    F = G * N
    dN = -F / DR
    dN = dN.at[1:].add(F[:-1] / DR)
    # Nucleation burst into the seed cell.
    J = anuc * jnp.exp(-(t - T0) ** 2 / (2 * TAU ** 2))
    dN = dN.at[JSTAR].add(J / DR)
    return dN


def observe(history, p):
    """UV-Vis spectra at the observation times: A = (N . DR) @ KERNEL^T."""
    Nsel = history[_IDX]                       # (n_obs, K)
    return (Nsel * DR) @ _KERNEL.T             # (n_obs, n_lam)


def build_model():
    pbm = PopulationBalanceModel('qd_growth')
    pbm.set_coordinate('r', R)
    pbm.parameter('kg', value=0.010, bounds=(1e-3, 0.1))
    pbm.parameter('anuc', value=0.010, bounds=(1e-3, 0.1))
    pbm.set_initial_state(jnp.zeros(K))
    pbm.set_dynamics(step, t_end=TF, nt=NT, scheme='euler')
    pbm.set_observation(observe)
    return pbm


def mean_radius(N_rows):
    """Mass-weighted (r^3) mean radius per row."""
    w = N_rows * R ** 3
    denom = np.maximum(w.sum(axis=1), 1e-12)
    return (w @ R) / denom


def make_figure(ro, A_data, N_true, N_fit, N_naive):
    """Summary figure: UV-Vis fit, size distribution, mean radius, rate recovery.

    Optional and guarded -- a missing matplotlib simply skips the figure. Saves
    ``Ex_8_qd_growth_uvvis.png`` next to this script.
    """
    try:
        import matplotlib
        import matplotlib.pyplot as plt
    except ImportError:
        print("\n(matplotlib not installed, skipping figure)")
        return

    A_fit = np.asarray(observe(jnp.asarray(ro.state_history), ro.P))

    def _shape(N):
        return N[-1] / max(N[-1].sum(), 1e-12)

    fig, ax = plt.subplots(2, 2, figsize=(11, 8))

    for s in (0, 3, 6, 9):
        line, = ax[0, 0].plot(LAM, A_fit[s], lw=1.5)
        ax[0, 0].plot(LAM, A_data[s], ls='', marker='.', ms=3, alpha=0.5,
                      color=line.get_color())
        ax[0, 0].annotate(f't={T_OBS[s]:.0f}', (LAM[-1], A_fit[s, -1]),
                          fontsize=7, color=line.get_color())
    ax[0, 0].set(title='UV-Vis: data (dots) vs mechanism fit (lines)',
                 xlabel='wavelength (nm)', ylabel='absorbance')

    ax[0, 1].plot(R, _shape(N_true), 'k-', lw=2, label='true')
    ax[0, 1].plot(R, _shape(N_fit), 'C0--', lw=1.8, label='mechanism')
    ax[0, 1].plot(R, _shape(N_naive), 'C3:', lw=1.8, label='naive inversion')
    ax[0, 1].set(title='Final size distribution (normalized shape)',
                 xlabel='particle radius  r (nm)', ylabel='fraction')
    ax[0, 1].legend(fontsize=8)

    ax[1, 0].plot(T_OBS, mean_radius(N_true), 'k-o', ms=4, label='true')
    ax[1, 0].plot(T_OBS, mean_radius(N_fit), 'C0--s', ms=4, label='mechanism')
    ax[1, 0].plot(T_OBS, mean_radius(N_naive), 'C3:^', ms=4,
                  label='naive inversion')
    ax[1, 0].set(title='Mean particle radius vs time',
                 xlabel='time', ylabel='mean radius (nm)')
    ax[1, 0].legend(fontsize=8)

    names, tv = ['kg', 'anuc'], [KG_TRUE, ANUC_TRUE]
    ev = [ro.P['kg'], ro.P['anuc']]
    x = np.arange(len(names))
    ax[1, 1].bar(x - 0.2, tv, 0.4, label='true')
    ax[1, 1].bar(x + 0.2, ev, 0.4, label='estimated')
    for xi, (t, e) in enumerate(zip(tv, ev)):
        ax[1, 1].annotate(f'{abs(e - t) / t * 100:.1f}%', (xi, max(t, e)),
                          ha='center', va='bottom', fontsize=8)
    ax[1, 1].set_xticks(x)
    ax[1, 1].set_xticklabels(names)
    ax[1, 1].set(title='Rate-constant recovery', ylabel='value')
    ax[1, 1].legend(fontsize=8)

    fig.suptitle('Ex 8: quantum-dot growth -- mechanism vs naive inversion',
                 y=1.02)
    fig.tight_layout()
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       'Ex_8_qd_growth_uvvis.png')
    fig.savefig(out, dpi=130, bbox_inches='tight')
    print(f"\n  wrote {out}")


def main():
    # Synthetic data at the true parameters, 2% max-amplitude noise.
    truth = build_model().simulate({'kg': KG_TRUE, 'anuc': ANUC_TRUE})
    A_true = np.asarray(observe(jnp.asarray(truth.state_history),
                                {'kg': KG_TRUE, 'anuc': ANUC_TRUE}))
    rng = np.random.default_rng(0)
    A_data = A_true + 0.02 * A_true.max() * rng.standard_normal(A_true.shape)

    print("Fitting growth kinetics to the UV-Vis time series...")
    pbm = build_model()
    pbm.add_data(A_data)
    ro = pbm.run_opt(verbose=True)

    print(f"\n  {'param':8s} {'true':>10s} {'estimated':>12s} {'error%':>9s}")
    print(f"  {'-' * 42}")
    for name, tv in [('kg', KG_TRUE), ('anuc', ANUC_TRUE)]:
        ev = ro.P[name]
        print(f"  {name:8s} {tv:>10.4f} {ev:>12.4f} {abs(ev - tv) / tv * 100:>8.2f}%")

    # Mechanism-reconstructed distribution vs the naive per-spectrum inversion.
    N_true = np.asarray(truth.state_history)[IDX_OBS]
    N_fit = ro.state_history[IDX_OBS]
    N_naive = PopulationBalanceModel.nnls_inversion(A_data, KERNEL * DR)

    r_true = mean_radius(N_true)
    rmse_fit = np.sqrt(np.mean((mean_radius(N_fit) - r_true) ** 2))
    rmse_naive = np.sqrt(np.mean((mean_radius(N_naive) - r_true) ** 2))

    def shape_l1(N):
        row = N[-1] / max(N[-1].sum(), 1e-12)
        return row
    l1_fit = np.abs(shape_l1(N_fit) - shape_l1(N_true)).sum()
    l1_naive = np.abs(shape_l1(N_naive) - shape_l1(N_true)).sum()

    print(f"\n  {'recovery':28s} {'mean-r RMSE (nm)':>16s} {'final-dist L1':>14s}")
    print(f"  {'-' * 60}")
    print(f"  {'naive per-spectrum inversion':28s} {rmse_naive:>16.3f} {l1_naive:>14.3f}")
    print(f"  {'mechanism-constrained fit':28s} {rmse_fit:>16.3f} {l1_fit:>14.3f}")
    print("\n  The mechanism ties every time point together and regularizes the "
          "ill-posed inversion.")

    make_figure(ro, A_data, N_true, N_fit, N_naive)
    return ro


if __name__ == '__main__':
    main()
