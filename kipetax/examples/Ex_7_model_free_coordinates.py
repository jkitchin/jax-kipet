"""Model-free collective variables from a spectral matrix D(t, lambda).

SYNTHETIC DATA. Every spectrum, rate constant, band position, noise level, and
concentration in this example is generated by the kipetax models defined below.
Nothing here is measured. The numbers are illustrative, chosen only to be
qualitatively like a real vibrational kinetics experiment, and they are neither
fitted to nor validated against laboratory data. The example demonstrates method
behaviour, not physical parameter values.

These are model-free analyses. They fit no mechanism. Given only the spectral
matrix D(t, lambda), they ask three questions: how many independent processes are
present, how fast do they relax, and is there a single low-dimensional coordinate
that the spectral changes track. Two complementary methods answer different parts
of that question.

Dynamic mode decomposition (DMD, the discrete Koopman approximation) fits the
series as a small set of spatial modes, each evolving as exp(omega_j t). For
bilinear kinetics dc/dt = K c the continuous eigenvalues omega_j are exactly the
eigenvalues of the rate matrix K, that is, the relaxation rates, so a rank-3 DMD
reads the rates of A -> B -> C straight off the spectra with no mechanism
assumed. On the linear system it recovers k1 = 0.9 and k2 = 0.5. The spatial
modes phi_j are the difference spectra, telling what changes at each rate.

A diffusion map answers the geometric question. A single kinetic run traces a
one-dimensional curve through spectral space parametrized by one clock, time. Its
leading nontrivial coordinate psi_1 is a data-driven reaction coordinate,
monotone in the extent of reaction, and it stays one-dimensional even when
spectral interactions inflate the linear (PCA) embedding dimension from three to
five. The intrinsic dimension (one) is not the linear embedding dimension (three
for additive spectra, five once transient adducts break bilinearity). The extra
PCA components are curvature of the same one-dimensional curve, not new processes.

The second half is a stress test. DMD is a linear model of the dynamics, exact
only when the spectra are a sum of exp(omega t) modes. Training DMD on the first
half of a trajectory and predicting forward is essentially exact for the linear
A -> B -> C system but diverges badly for a nonlinear A -> B, 2B -> C system whose
dB/dt carries a quadratic -2 k2 B^2 sink. The rates reported for the nonlinear fit
are local linear surrogates for the dimerization step, not physical constants.
What survives the nonlinearity is geometry: a diffusion-map coordinate still
parametrizes the trajectory that no fixed set of linear modes can predict.

The concentrations for both systems are generated with kipetax ReactionModel
simulations, not analytic formulas and not a hand-rolled integrator. The
collocation solver returns the states at non-uniform collocation points, so each
profile is interpolated onto a uniform time grid before any DMD, because DMD's
omega = log(mu)/dt conversion assumes a uniform sampling interval dt.
"""
import os
import sys
import time

import numpy as np
from scipy.spatial.distance import pdist, squareform

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..'))

from kipetax import ReactionModel


# ---------------------------------------------------------------------------
# Spectra (copied from Ex_4_spectral_interactions.py). Two adduct bands are
# added so that transient interactions inflate the linear rank from 3 to 5.
# ---------------------------------------------------------------------------
NU = np.linspace(300.0, 1700.0, 100)     # Raman shift, cm^-1
TFINAL = 10.0                            # observation window, arbitrary time units
N_UNIFORM = 60                           # points on the uniform DMD/diffusion grid

K1_LIN, K2_LIN = 0.9, 0.5               # linear A -> B -> C
K1_NON, K2_NON = 0.8, 2.5              # nonlinear A -> B, 2B -> C
A0 = 1.0
G_AB, G_BC = 1.6, 1.6                  # adduct band strengths


def lorentzian(nu, nu0, gamma, amp):
    return amp * gamma ** 2 / ((nu - nu0) ** 2 + gamma ** 2)


def spec_A(nu):
    return lorentzian(nu, 520.0, 15.0, 1.0) + lorentzian(nu, 1000.0, 20.0, 0.6)


def spec_B(nu):
    return lorentzian(nu, 700.0, 18.0, 0.8) + lorentzian(nu, 1350.0, 25.0, 0.7)


def spec_C(nu):
    return lorentzian(nu, 900.0, 20.0, 0.9) + lorentzian(nu, 1600.0, 22.0, 1.0)


def spec_adduct_AB(nu):
    """Band unique to the transient A.B adduct (present only when A and B overlap)."""
    return lorentzian(nu, 1150.0, 20.0, 0.7)


def spec_adduct_BC(nu):
    """Band unique to the transient B.C adduct, added to reach a linear rank of 5."""
    return lorentzian(nu, 1450.0, 20.0, 0.7)


# ---------------------------------------------------------------------------
# Concentration generation via kipetax (no analytic profiles, no hand-rolled RK4)
# ---------------------------------------------------------------------------
def _simulate_to_uniform(model, nfe):
    """Simulate a ReactionModel and interpolate its states onto a uniform grid.

    Parameters
    ----------
    model : ReactionModel
        A fully specified model with ODEs and initial conditions. ``set_time`` is
        applied here; the caller must not have called ``simulate`` yet.
    nfe : int
        Number of finite elements for the collocation discretization.

    Returns
    -------
    t : ndarray, shape (N_UNIFORM,)
        Uniform time grid on [0, TFINAL].
    C : ndarray, shape (N_UNIFORM, 3)
        Columns are the A, B, C concentration profiles on the uniform grid.
    """
    model.set_time(TFINAL)
    model.set_discretization(nfe=nfe, ncp=3)
    model.simulate()                    # raises RuntimeError if collocation fails

    Z = model.results_dict['simulator'].Z
    t = np.linspace(0.0, TFINAL, N_UNIFORM)
    t_coll = Z.index.values             # non-uniform collocation points
    C = np.column_stack([np.interp(t, t_coll, Z[c].values) for c in ('A', 'B', 'C')])
    return t, C


def concentrations_linear():
    """Generate A -> B -> C concentrations with kipetax (k1=0.9, k2=0.5)."""
    r = ReactionModel('linear_ABC')
    k1 = r.parameter('k1', value=K1_LIN, bounds=(0, 10), fixed=True)
    k2 = r.parameter('k2', value=K2_LIN, bounds=(0, 10), fixed=True)
    A = r.component('A', value=A0)
    B = r.component('B', value=0.0)
    C = r.component('C', value=0.0)
    r.add_ode('A', -k1 * A)
    r.add_ode('B', k1 * A - k2 * B)
    r.add_ode('C', k2 * B)
    return _simulate_to_uniform(r, nfe=240)


def concentrations_nonlinear():
    """Generate A -> B, 2B -> C concentrations with kipetax (k1=0.8, k2=2.5).

    The dimerization step gives dB/dt a quadratic -2 k2 B^2 sink, so the
    trajectory is not a sum of exponentials. This is a perfectly ordinary
    ReactionModel; the nonlinearity lives entirely in the ODE expression.
    """
    r = ReactionModel('nonlinear_dimer')
    k1 = r.parameter('k1', value=K1_NON, bounds=(0, 10), fixed=True)
    k2 = r.parameter('k2', value=K2_NON, bounds=(0, 10), fixed=True)
    A = r.component('A', value=A0)
    B = r.component('B', value=0.0)
    C = r.component('C', value=0.0)
    r.add_ode('A', -k1 * A)
    r.add_ode('B', k1 * A - 2 * k2 * B * B)
    r.add_ode('C', k2 * B * B)
    return _simulate_to_uniform(r, nfe=120)


def spectra_additive(C):
    """Bilinear Beer-Lambert spectra D = sum_k c_k s_k, shape (n_time, n_lambda)."""
    cA, cB, cC = C[:, 0], C[:, 1], C[:, 2]
    return (np.outer(cA, spec_A(NU))
            + np.outer(cB, spec_B(NU))
            + np.outer(cC, spec_C(NU)))


def spectra_interacting(C):
    """Additive spectra plus two transient-adduct bands that break bilinearity.

    The A.B band scales as c_A c_B and the B.C band as c_B c_C. Each is a rank-1
    outer product with a new temporal profile, so together they raise the linear
    rank of the spectral matrix from 3 to 5.
    """
    cA, cB, cC = C[:, 0], C[:, 1], C[:, 2]
    D = spectra_additive(C)
    D = D + G_AB * np.outer(cA * cB, spec_adduct_AB(NU))
    D = D + G_BC * np.outer(cB * cC, spec_adduct_BC(NU))
    return D


# ---------------------------------------------------------------------------
# Dynamic mode decomposition (exact DMD)
# ---------------------------------------------------------------------------
def dmd(D, dt, r):
    """Exact DMD of a spectral time series.

    Parameters
    ----------
    D : ndarray, shape (n_time, n_lambda)
        Spectral matrix sampled on a uniform time grid.
    dt : float
        Uniform sampling interval. The continuous eigenvalues use log(mu)/dt,
        which is only valid for uniform sampling.
    r : int
        Rank of the SVD truncation.

    Returns
    -------
    omega : ndarray, shape (r,)
        Continuous-time eigenvalues, sorted by decreasing real part. The
        relaxation rates are -omega.real.
    modes : ndarray, shape (n_lambda, r)
        DMD spatial modes (difference spectra), ordered to match omega.
    """
    X, X2 = D[:-1].T, D[1:].T                       # (n_lambda, n_time-1)
    U, s, Vt = np.linalg.svd(X, full_matrices=False)
    U, s, V = U[:, :r], s[:r], Vt[:r].T
    Atil = U.conj().T @ X2 @ V @ np.diag(1.0 / s)
    mu, W = np.linalg.eig(Atil)
    omega = np.log(mu) / dt
    modes = X2 @ V @ np.diag(1.0 / s) @ W
    order = np.argsort(omega.real)[::-1]
    return omega[order], modes[:, order]


def dmd_train_predict(D, r, m_train, t, dt):
    """Fit DMD on the first ``m_train`` snapshots and predict the full trajectory.

    Parameters
    ----------
    D : ndarray, shape (n_time, n_lambda)
        Spectral matrix on a uniform time grid.
    r : int
        SVD truncation rank.
    m_train : int
        Number of leading snapshots used to fit the linear operator.
    t : ndarray, shape (n_time,)
        Uniform time grid (used to propagate the modes).
    dt : float
        Uniform sampling interval.

    Returns
    -------
    Dpred : ndarray, shape (n_time, n_lambda)
        Reconstruction and forward prediction from the initial spectrum.
    omega : ndarray, shape (r,)
        Continuous-time eigenvalues, sorted by decreasing real part.
    """
    Dtr = D[:m_train]
    X, X2 = Dtr[:-1].T, Dtr[1:].T
    U, s, Vt = np.linalg.svd(X, full_matrices=False)
    U, s, V = U[:, :r], s[:r], Vt[:r].T
    Atil = U.conj().T @ X2 @ V @ np.diag(1.0 / s)
    mu, W = np.linalg.eig(Atil)
    omega = np.log(mu) / dt
    Phi = X2 @ V @ np.diag(1.0 / s) @ W
    b = np.linalg.lstsq(Phi, D[0], rcond=None)[0]
    Dpred = (Phi @ (b[:, None] * np.exp(np.outer(omega, t)))).real.T
    order = np.argsort(omega.real)[::-1]
    return Dpred, omega[order]


# ---------------------------------------------------------------------------
# Diffusion map (geometric reaction coordinate)
# ---------------------------------------------------------------------------
def diffusion_map(D):
    """Leading diffusion-map coordinate of a set of spectra.

    Parameters
    ----------
    D : ndarray, shape (n_time, n_lambda)
        Each row is one spectrum; rows are treated as points in R^n_lambda.

    Returns
    -------
    psi1 : ndarray, shape (n_time,)
        The leading nontrivial diffusion coordinate psi_1 (psi_0 is constant).
    """
    Dm = squareform(pdist(D))
    eps = np.median(Dm[Dm > 0]) ** 2
    Wm = np.exp(-Dm ** 2 / eps)
    P = Wm / Wm.sum(axis=1, keepdims=True)          # row-stochastic Markov matrix
    val, vec = np.linalg.eig(P)
    order = np.argsort(val.real)[::-1]
    return vec.real[:, order[1]]


def linear_rank(D, thr):
    """Count singular values above a noise-floor threshold."""
    sv = np.linalg.svd(D, compute_uv=False)
    return int((sv > thr).sum()), sv


def rmse(a, b):
    return float(np.sqrt(np.mean((a - b) ** 2)))


