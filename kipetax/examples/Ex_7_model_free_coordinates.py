# Analyses
# ---------------------------------------------------------------------------
def part1_collective_variables(t_lin, C_lin, results):
    """DMD rates, linear-rank inflation, and the diffusion-map reaction coordinate."""
    dt = float(t_lin[1] - t_lin[0])
    cA = C_lin[:, 0]
    extent = 1.0 - cA / cA[0]                        # monotone extent of A consumption

    D_add = spectra_additive(C_lin)
    D_int = spectra_interacting(C_lin)

    rng = np.random.default_rng(0)
    noise = 2e-3
    D_add_n = D_add + noise * rng.standard_normal(D_add.shape)
    D_int_n = D_int + noise * rng.standard_normal(D_int.shape)

    print("=" * 72)
    print("COLLECTIVE VARIABLES FROM SPECTRA (no species, no mechanism)")
    print("(SYNTHETIC, illustrative data, not experimental measurements.)")
    print("=" * 72)

    # (1) DMD reads the kinetic eigenvalues straight off the additive spectra.
    omega, _ = dmd(D_add_n, dt, r=3)
    rates = np.sort(-omega.real)
    recovered = np.sort(rates[rates > 1e-2])
    print("\n[1] DMD (dynamical CVs) on additive A->B->C spectra, rank 3:")
    print(f"    continuous eigenvalues (rates): {np.round(-omega.real, 3)}")
    print(f"    -> recovered rate constants {np.round(recovered, 3)}  "
          f"(true k2={K2_LIN}, k1={K1_LIN})")
    print("    No mechanism was assumed; the exp(-k t) modes fall out of the data.")

    # (2) Linear rank: interactions inflate the PCA embedding dimension.
    # Noise-edge singular value of an m x n Gaussian block is ~sigma(sqrt m + sqrt n);
    # a threshold at 2.5x that edge keeps genuine modes and rejects the noise floor.
    thr = 2.5 * noise * (np.sqrt(D_add.shape[0]) + np.sqrt(D_add.shape[1]))
    ra, sv_a = linear_rank(D_add_n, thr)
    ri, sv_i = linear_rank(D_int_n, thr)
    print(f"\n[2] Linear rank (PCA embedding dim) at noise floor thr={thr:.3f}:")
    print(f"    additive={ra}   interacting={ri}   (interaction inflates it)")
    print(f"    additive singular values     : {np.round(sv_a[:7], 3)}")
    print(f"    interacting singular values  : {np.round(sv_i[:7], 3)}")

    # (3) Diffusion-map reaction coordinate stays one-dimensional either way.
    psi_a = diffusion_map(D_add)
    psi_i = diffusion_map(D_int)
    corr_a = abs(np.corrcoef(psi_a, extent)[0, 1])
    corr_i = abs(np.corrcoef(psi_i, extent)[0, 1])
    print("\n[3] Diffusion-map coordinate psi_1 (geometric CV) vs extent:")
    print(f"    corr(psi_1, extent):  additive={corr_a:.3f}   interacting={corr_i:.3f}")
    print("    -> one 1-D reaction coordinate, monotone in extent, recovered even")
    print(f"       though interactions push the linear rank to {ri}. Intrinsic")
    print("       dimension (1) is not the linear embedding dimension (3 or 5).")

    results.update(dict(dmd_rates=recovered, rank_add=ra, rank_int=ri,
                        corr_add=corr_a, corr_int=corr_i))


def part2_dmd_stress_test(t_lin, C_lin, t_non, C_non, results):
    """Forward-prediction stress test: linear DMD is exact, nonlinear DMD diverges."""
    dt = float(t_lin[1] - t_lin[0])
    m = N_UNIFORM // 2                               # train on the first half

    lin = spectra_additive(C_lin)
    non = spectra_additive(C_non)

    Dp_lin, om_lin = dmd_train_predict(lin, 3, m, t_lin, dt)
    Dp_non, om_non = dmd_train_predict(non, 3, m, t_non, dt)

    train_lin, pred_lin = rmse(Dp_lin[:m], lin[:m]), rmse(Dp_lin[m:], lin[m:])
    train_non, pred_non = rmse(Dp_non[:m], non[:m]), rmse(Dp_non[m:], non[m:])
    ratio = pred_non / pred_lin

    print("\n" + "=" * 72)
    print("WHERE LINEAR KOOPMAN (DMD) BREAKS")
    print("(SYNTHETIC, illustrative data, not experimental measurements.)")
    print("=" * 72)
    print("\nDMD trained on the first half, predicting the full trajectory:")
    print(f"  linear A->B->C     train RMSE {train_lin:.1e}   PREDICT RMSE {pred_lin:.1e}")
    print(f"  nonlinear 2B->C    train RMSE {train_non:.1e}   PREDICT RMSE {pred_non:.1e}")
    print(f"  -> nonlinear prediction error is ~{ratio:.0e}x the linear one.")
    print(f"\n  DMD rates, linear    : {np.round(np.sort(-om_lin.real), 3)}  "
          f"(true 0, {K2_LIN}, {K1_LIN})")
    print(f"  DMD rates, nonlinear : {np.round(np.sort(-om_non.real), 3)}  "
          f"({K1_NON} is k1; the rest are spurious linear surrogates for 2B->C)")

    # Geometry survives where the linear-dynamics model fails.
    psi = diffusion_map(non)
    arc = np.concatenate([[0.0],
                          np.cumsum(np.linalg.norm(np.diff(non, axis=0), axis=1))])
    arc /= arc[-1]
    corr_arc = abs(np.corrcoef(psi, arc)[0, 1])
    print(f"\n  Nonlinear reaction coordinate: corr(diffusion psi_1, arc length) "
          f"= {corr_arc:.3f}")
    print("  -> geometry survives: a 1-D nonlinear coordinate still parametrizes")
    print("     the trajectory that no fixed set of linear modes can predict.")

    results.update(dict(train_lin=train_lin, pred_lin=pred_lin,
                        train_non=train_non, pred_non=pred_non, ratio=ratio,
                        rates_non=np.sort(-om_non.real), corr_arc=corr_arc))
    return lin, non, Dp_lin, Dp_non, m, psi, arc


def make_figure(t, om_dmd, sv_a, sv_i, thr, extent, psi_a, psi_i,
                lin, non, Dp_non, m, psi_non, arc):
    """Optional summary figure. Skipped if matplotlib is unavailable."""
    try:
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
    except ImportError:
        print("\n(matplotlib not installed, skipping figure)")
        return

    ipeak = int(np.argmin(np.abs(NU - 1600.0)))
    fig, ax = plt.subplots(2, 3, figsize=(16, 9))

    ax[0, 0].plot(t, np.exp(-K1_LIN * t), 'C0', lw=2, label=f'true exp(-k1 t), k1={K1_LIN}')
    ax[0, 0].plot(t, np.exp(-K2_LIN * t), 'C1', lw=2, label=f'true exp(-k2 t), k2={K2_LIN}')
    for j, om in enumerate(om_dmd):
        rate = -om.real
        if rate > 1e-2:
            ax[0, 0].plot(t, np.exp(-rate * t), 'k--', lw=1.2,
                          label='DMD mode' if j == 1 else None)
    ax[0, 0].set(title='DMD modes recover the kinetic eigenvalues',
                 xlabel='time', ylabel='mode amplitude')
    ax[0, 0].legend(fontsize=8)

    n = np.arange(1, 8)
    ax[0, 1].semilogy(n, sv_a[:7], 'o-', label='additive')
    ax[0, 1].semilogy(n, sv_i[:7], 's-', label='interacting')
    ax[0, 1].axhline(thr, color='k', ls=':', lw=1, label='noise floor')
    ax[0, 1].set(title='Linear (PCA) rank: 3 additive -> 5 interacting',
                 xlabel='component', ylabel='singular value')
    ax[0, 1].legend(fontsize=8)

    ax[0, 2].plot(extent, psi_a, 'o', ms=4, label='additive')
    ax[0, 2].plot(extent, psi_i, 's', ms=4, label='interacting')
    ax[0, 2].set(title='Diffusion-map psi_1 = 1-D reaction coordinate',
                 xlabel='extent of reaction (1 - cA/cA0)', ylabel='psi_1 (a.u.)')
    ax[0, 2].legend(fontsize=8)

    ax[1, 0].plot(t, non[:, ipeak], 'k', lw=2, label='true (nonlinear)')
    ax[1, 0].plot(t, Dp_non[:, ipeak], 'C3--', lw=2, label='DMD prediction')
    ax[1, 0].axvline(t[m], color='0.6', ls=':', lw=1)
    ax[1, 0].set(title='Nonlinear: DMD extrapolation diverges',
                 xlabel='time', ylabel='intensity @1600 cm-1')
    ax[1, 0].legend(fontsize=8)

    e_non = np.sqrt(((Dp_non - non) ** 2).mean(axis=1))
    ax[1, 1].semilogy(t, np.maximum(e_non, 1e-16), 'C3', lw=2, label='nonlinear 2B->C')
    ax[1, 1].axvline(t[m], color='0.6', ls=':', lw=1)
    ax[1, 1].set(title='Prediction error vs time (train | predict)',
                 xlabel='time', ylabel='RMSE')
    ax[1, 1].legend(fontsize=8)

    ax[1, 2].plot(arc, psi_non, 'o', ms=4, color='C2')
    ax[1, 2].set(title='Diffusion coordinate psi_1 vs arc length (nonlinear)',
                 xlabel='arc length along trajectory', ylabel='psi_1 (a.u.)')

    fig.tight_layout()
    out = os.path.join(os.path.dirname(__file__), 'Ex_7_model_free_coordinates.png')
    fig.savefig(out, dpi=120)
    plt.close(fig)
    print(f"\nFigure written to {out}")


def main():
    t0 = time.time()
    results = {}

    print("Generating concentrations with kipetax ReactionModel simulations...")
    t_lin, C_lin = concentrations_linear()
    t_non, C_non = concentrations_nonlinear()

    part1_collective_variables(t_lin, C_lin, results)
    lin, non, Dp_lin, Dp_non, m, psi_non, arc = part2_dmd_stress_test(
        t_lin, C_lin, t_non, C_non, results)

    # Recompute the pieces the figure needs (kept out of the analyses' return
    # values to keep those focused on the reported numbers).
    dt = float(t_lin[1] - t_lin[0])
    rng = np.random.default_rng(0)
    noise = 2e-3
    D_add = spectra_additive(C_lin)
    D_int = spectra_interacting(C_lin)
    D_add_n = D_add + noise * rng.standard_normal(D_add.shape)
    D_int_n = D_int + noise * rng.standard_normal(D_int.shape)
    # Noise-edge singular value of an m x n Gaussian block is ~sigma(sqrt m + sqrt n);
    # a threshold at 2.5x that edge keeps genuine modes and rejects the noise floor.
    thr = 2.5 * noise * (np.sqrt(D_add.shape[0]) + np.sqrt(D_add.shape[1]))
    _, sv_a = linear_rank(D_add_n, thr)
    _, sv_i = linear_rank(D_int_n, thr)
    om_dmd, _ = dmd(D_add_n, dt, r=3)
    extent = 1.0 - C_lin[:, 0] / C_lin[0, 0]
    psi_a = diffusion_map(D_add)
    psi_i = diffusion_map(D_int)

    make_figure(t_lin, om_dmd, sv_a, sv_i, thr, extent, psi_a, psi_i,
                lin, non, Dp_non, m, psi_non, arc)

    print("\n" + "=" * 72)
    print(f"Total runtime: {time.time() - t0:.1f} s")
    print("=" * 72)
    return results


if __name__ == '__main__':
    main()
